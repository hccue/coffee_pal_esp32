#!/usr/bin/env python3
"""Generates src/font_data.h (anti-aliased glyph bitmaps) from assets/Nunito.ttf."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = [
    ("fontDigits", 50, 900, "0123456789"),
    ("fontText", 18, 800, "".join(chr(c) for c in range(32, 127))),
]


def glyphs(px, weight, chars):
    font = ImageFont.truetype(str(ROOT / "assets/Nunito.ttf"), px)
    font.set_variation_by_axes([weight])
    data, table = [], {}
    for ch in chars:
        box = font.getbbox(ch, anchor="ls")
        w, h = box[2] - box[0], box[3] - box[1]
        offset = len(data)
        if w > 0 and h > 0:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255, anchor="ls")
            data.extend(img.tobytes())
        table[ch] = (offset, w, h, box[0], box[1], round(font.getlength(ch)))
    return data, table


out = ["// Generated by tools/make_font.py. Do not edit.", "#pragma once", '#include "gfx.h"', ""]
for name, px, weight, chars in FONTS:
    data, table = glyphs(px, weight, chars)
    first, last = ord(chars[0]), ord(chars[-1])
    out.append(f"static const uint8_t {name}Bitmap[] = {{")
    out += [",".join(map(str, data[i:i + 40])) + "," for i in range(0, len(data), 40)]
    out.append("};")
    out.append(f"static const Glyph {name}Glyphs[] = {{")
    for ch in chars:
        out.append("  {%d,%d,%d,%d,%d,%d}," % table[ch])
    out.append("};")
    out.append(f"static const Font {name} = {{{name}Bitmap, {name}Glyphs, {first}, {last}}};")
    out.append("")
(ROOT / "src/font_data.h").write_text("\n".join(out))
